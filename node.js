// JavaScript was first officially released on December 4, 1995, when it was announced by Netscape and Sun Microsystems.
// Node.js was first released on May 27, 2009. It was created by Ryan Dahl, who officially introduced the open-source, server-side JavaScript runtime environment initially supporting Linux and Mac OS X.

// Node.js is a JavaScript runtime built on Chrome's V8 engine that allows JavaScript to execute outside the browser. It uses an event-driven, non-blocking I/O model
// JavaScript is the language. Node.js is a runtime environment that executes JavaScript and provides APIs that aren't part of JavaScript itself.
// require, fs, filesystem access, networking APIs, process, etc. are not features of the JavaScript language itself. Node provides them.

// V8 is Google's JavaScript engine. Its job includes compiling and executing JavaScript and managing things such as JavaScript memory and garbage collection.
// Node embeds V8, but:
// Node.js ≠ V8.
// Node contains V8 plus additional components that provide capabilities needed for server-side programs.
// This distinction makes a common interview question:
// "If Node.js uses V8, what does Node provide that V8 doesn't?" : Think about filesystem access, networking, timers, the event loop integration, processes, streams, etc.

